import {copyFile,mkdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
import path from 'node:path';
const require=createRequire(import.meta.url);
const root=path.dirname(require.resolve('tesseract.js/package.json'));
const core=path.dirname(require.resolve('tesseract.js-core/package.json'));
const lang=path.dirname(require.resolve('@tesseract.js-data/fra/package.json'));
await mkdir('public/ocr/core',{recursive:true});await mkdir('public/ocr/lang',{recursive:true});
await copyFile(path.join(root,'dist/worker.min.js'),'public/ocr/worker.min.js');
for(const name of ['tesseract-core-lstm.wasm.js','tesseract-core-simd-lstm.wasm.js','tesseract-core-relaxedsimd-lstm.wasm.js'])await copyFile(path.join(core,name),path.join('public/ocr/core',name));
await copyFile(path.join(lang,'4.0.0_best_int/fra.traineddata.gz'),'public/ocr/lang/fra.traineddata.gz');
await copyFile(path.join(root,'LICENSE.md'),'public/ocr/LICENSE-tesseract.txt');
console.log('Moteur OCR et langue française prêts, servis depuis la même origine.');
