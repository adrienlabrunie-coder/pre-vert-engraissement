export const CONCENTRE_FAMILLES = new Set([
  "cereale",
  "proteique",
  "coproduit",
  "aliment_complet",
]);

export function estConcentre(f: Feed): boolean {
  return CONCENTRE_FAMILLES.has(f.famille);
}

export function estFourrage(f: Feed): boolean {
  return (
    f.famille === "fourrage_humide" || f.famille === "fourrage_sec" || f.famille === "paille"
  );
}

/** Fourrage sec à brins longs (foin, paille) : indispensable pour faire ruminer */
export function estFourrageSec(f: Feed): boolean {
  return f.famille === "fourrage_sec" || f.famille === "paille";
}

